"""Writes windows/src/Nama.Core/L10n.Strings.g.cs from 30nama/Core/L10n.swift.

Both apps carry the same keys and translations. The Swift file is where they are written;
this copies its keys and its three tables, so the Windows app never drifts from it. Run it
after the Mac side adds or changes a string; a test fails until then.

    python windows/tools/gen-l10n.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
swift = (root / "30nama/Core/L10n.swift").read_text(encoding="utf-8")

enum = re.search(r"enum S: String, CaseIterable \{(.*?)\n\}", swift, re.S).group(1)
keys = [k.strip() for line in re.findall(r"case (.+)", enum) for k in line.split(",") if k.strip()]

def table(name):
    body = re.search(r"static let %s: \[S: String\] = \[(.*?)\n    \]" % name, swift, re.S).group(1)
    return re.findall(r'\.(\w+): "((?:[^"\\]|\\.)*)"', body)

def csharp(value):
    # Swift escapes are \" \\ \n and \u{XXXX}; C# takes the first three as they are.
    return re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: "\\u%04X" % int(m.group(1), 16), value)

out = [
    "// <auto-generated>",
    "// Written by windows/tools/gen-l10n.py from 30nama/Core/L10n.swift. Do not edit by hand.",
    "// </auto-generated>",
    "namespace Nama.Core;",
    "",
    "/// <summary>Interface string keys, named as in the Mac app so both read the same tables.</summary>",
    "#pragma warning disable IDE1006",
    "public enum S",
    "{",
]
out += ["    %s," % k for k in keys]
out += ["}", "#pragma warning restore IDE1006", "", "public sealed partial class Loc", "{"]
for name in ("en", "fa", "ar"):
    out.append("    internal static readonly IReadOnlyDictionary<S, string> %s = new Dictionary<S, string>" % name.capitalize())
    out.append("    {")
    for key, value in table(name):
        out.append('        [S.%s] = "%s",' % (key, csharp(value)))
    out.append("    };")
    out.append("")
out[-1] = "}"
target = root / "windows/src/Nama.Core/L10n.Strings.g.cs"
target.write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", target.relative_to(root), "with", len(keys), "keys")
